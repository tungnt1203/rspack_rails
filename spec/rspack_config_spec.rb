# frozen_string_literal: true

require "tmpdir"
require "rspack_rails/rspack_config"

RSpec.describe RspackRails::RspackConfig do
  # config/rspack/rails.mjs itself, the file RspackConfig::BASE names.
  let(:base) { RspackRails::ManagedFile::BASE }

  around do |example|
    Dir.mktmpdir do |dir|
      @root = Pathname(dir)
      example.run
    end
  end

  def write(path, content = "")
    file = @root.join(path)
    file.dirname.mkpath
    file.write(content)
  end

  def synced
    RspackRails::ManagedFile::SyncResult.new(file: base, written: true, backup: nil)
  end

  it "stamps the gem version into config/rspack/rails.mjs" do
    expect(base.content).to include(%(export const VERSION = "#{RspackRails::VERSION}"))
    expect(base.content).not_to include("__RSPACK_RAILS_VERSION__")
  end

  it "knows a config built on config/rspack/rails.mjs from a standalone one" do
    expect(described_class.managed?(@root)).to be(false)
    write("rspack.config.mjs", %(import { railsConfig } from "./config/rspack/rails.mjs";))
    expect(described_class.managed?(@root)).to be(true)
    write("rspack.config.mjs", %(export default defineConfig({ entry: {} });))
    expect(described_class.managed?(@root)).to be(false)
  end

  it "writes config/rspack/rails.mjs when missing or outdated, and leaves a current one alone" do
    expect(base.sync(@root).written).to be(true)
    expect(@root.join("config/rspack/rails.mjs").read).to eq(base.content)
    expect(base.sync(@root).written).to be(false)

    write("config/rspack/rails.mjs", older_managed)
    expect(base.current?(@root)).to be(false)
    expect(base.sync(@root)).to eq(synced)
    expect(base.current?(@root)).to be(true)
  end

  it "stamps a checksum of the content, so a hand edit can be told from an older version" do
    expect(base.content).to match(%r{^// Checksum: [0-9a-f]{16} })
    write("config/rspack/rails.mjs", base.content)
    expect(base.edited?(@root)).to be(false)

    write("config/rspack/rails.mjs", base.content.sub("cheap-module-source-map", "eval"))
    expect(base.edited?(@root)).to be(true)
  end

  it "saves a file without a checksum, from before 0.17.0, before replacing it" do
    write("config/rspack/rails.mjs", %(// Generated by rspack_rails 0.16.0\nexport const VERSION = "0.16.0";\n))
    expect(base.edited?(@root)).to be(true)
    expect(base.sync(@root).backup.to_s).to start_with("tmp/rspack_rails/")
  end

  it "saves hand edits to tmp/rspack_rails before replacing them" do
    edited = base.content.sub("cheap-module-source-map", "eval")
    write("config/rspack/rails.mjs", edited)

    result = base.sync(@root)
    expect(result.written).to be(true)
    expect(result.backup.to_s).to match(%r{\Atmp/rspack_rails/rails-\d{14}\.mjs\z})
    expect(@root.join(result.backup).read).to eq(edited)
    expect(base.current?(@root)).to be(true)
    expect(base.edits_message(result.backup)).to include(result.backup.to_s, "railsConfig")
  end

  it "reports the state of config/rspack/rails.mjs" do
    expect(base.state(@root)).to eq(:missing)
    write("config/rspack/rails.mjs", older_managed)
    expect(base.state(@root)).to eq(:outdated)
    write("config/rspack/rails.mjs", base.content.sub("cheap-module-source-map", "eval"))
    expect(base.state(@root)).to eq(:edited)
    base.sync(@root)
    expect(base.state(@root)).to eq(:current)
  end

  it "ships an app config that imports the base" do
    template = File.read(File.expand_path("../lib/install/rspack.config.mjs", __dir__))
    expect(template).to include(%(from "./config/rspack/rails.mjs"))
  end
end
