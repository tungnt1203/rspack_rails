# frozen_string_literal: true

require "tmpdir"
require "rspack_rails/rspack_config"

RSpec.describe RspackRails::RspackConfig do
  around do |example|
    Dir.mktmpdir do |dir|
      @root = Pathname(dir)
      example.run
    end
  end

  def write(path, content = "")
    file = @root.join(path)
    file.dirname.mkpath
    file.write(content)
  end

  it "stamps the gem version into config/rspack/rails.mjs" do
    expect(described_class.base_content).to include(%(export const VERSION = "#{RspackRails::VERSION}"))
    expect(described_class.base_content).not_to include("__RSPACK_RAILS_VERSION__")
  end

  it "knows a config built on config/rspack/rails.mjs from a standalone one" do
    expect(described_class.managed?(@root)).to be(false)
    write("rspack.config.mjs", %(import { railsConfig } from "./config/rspack/rails.mjs";))
    expect(described_class.managed?(@root)).to be(true)
    write("rspack.config.mjs", %(export default defineConfig({ entry: {} });))
    expect(described_class.managed?(@root)).to be(false)
  end

  it "writes config/rspack/rails.mjs when missing or outdated, and leaves a current one alone" do
    expect(described_class.sync(@root).written).to be(true)
    expect(@root.join("config/rspack/rails.mjs").read).to eq(described_class.base_content)
    expect(described_class.sync(@root).written).to be(false)

    write("config/rspack/rails.mjs", "// from rspack_rails 0.0.1")
    expect(described_class.current?(@root)).to be(false)
    expect(described_class.sync(@root)).to eq(described_class::SyncResult.new(written: true, backup: nil))
    expect(described_class.current?(@root)).to be(true)
  end

  it "stamps a checksum of the content, so a hand edit can be told from an older version" do
    expect(described_class.base_content).to match(%r{^// Checksum: [0-9a-f]{16} })
    write("config/rspack/rails.mjs", described_class.base_content)
    expect(described_class.edited?(@root)).to be(false)

    write("config/rspack/rails.mjs", described_class.base_content.sub("cheap-module-source-map", "eval"))
    expect(described_class.edited?(@root)).to be(true)
  end

  it "does not count a file from before 0.17.0, which has no checksum, as edited" do
    write("config/rspack/rails.mjs", %(// Generated by rspack_rails 0.16.0\nexport const VERSION = "0.16.0";\n))
    expect(described_class.edited?(@root)).to be(false)
    expect(described_class.sync(@root)).to eq(described_class::SyncResult.new(written: true, backup: nil))
  end

  it "saves hand edits to tmp/rspack_rails before replacing them" do
    edited = described_class.base_content.sub("cheap-module-source-map", "eval")
    write("config/rspack/rails.mjs", edited)

    result = described_class.sync(@root)
    expect(result.written).to be(true)
    expect(result.backup.to_s).to match(%r{\Atmp/rspack_rails/rails-\d{14}\.mjs\z})
    expect(@root.join(result.backup).read).to eq(edited)
    expect(described_class.current?(@root)).to be(true)
    expect(described_class.edits_message(result.backup)).to include(result.backup.to_s, "railsConfig")
  end

  it "reports the state of config/rspack/rails.mjs" do
    expect(described_class.state(@root)).to eq(:missing)
    write("config/rspack/rails.mjs", "// from rspack_rails 0.0.1")
    expect(described_class.state(@root)).to eq(:outdated)
    write("config/rspack/rails.mjs", described_class.base_content.sub("cheap-module-source-map", "eval"))
    expect(described_class.state(@root)).to eq(:edited)
    described_class.sync(@root)
    expect(described_class.state(@root)).to eq(:current)
  end

  it "ships an app config that imports the base" do
    template = File.read(File.expand_path("../lib/install/rspack.config.mjs", __dir__))
    expect(template).to include(%(from "./config/rspack/rails.mjs"))
  end
end
