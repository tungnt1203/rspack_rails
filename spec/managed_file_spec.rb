# frozen_string_literal: true

require "tmpdir"
require "rspack_rails/managed_file"

RSpec.describe RspackRails::ManagedFile do
  around do |example|
    Dir.mktmpdir do |dir|
      @root = Pathname(dir)
      example.run
    end
  end

  let(:stimulus) { described_class::STIMULUS }
  let(:react) { described_class::REACT }

  def write(path, content)
    file = @root.join(path)
    file.dirname.mkpath
    file.write(content)
  end

  def read(path)
    @root.join(path).read
  end

  it "stamps the gem version and a checksum into the Stimulus and React loaders" do
    [stimulus, react].each do |file|
      expect(file.content).to include("Generated by rspack_rails #{RspackRails::VERSION}")
      expect(file.content).to match(%r{^// Checksum: [0-9a-f]{16}$})
      expect(file.content).not_to include("__RSPACK_RAILS_")
    end
  end

  it "syncs config/rspack/rails.mjs always, and a loader only once its installer added it" do
    expect(described_class.sync_all(@root).map(&:path)).to eq(["config/rspack/rails.mjs"])
    expect(stimulus.exist?(@root)).to be(false)

    expect(stimulus.sync(@root, create: true).written).to be(true)
    expect(read(stimulus.path)).to eq(stimulus.content)
    expect(described_class.sync_all(@root)).to eq([])
  end

  it "replaces a loader from another version without a backup" do
    write(react.path, older_managed(react))
    expect(react.state(@root)).to eq(:outdated)

    result = react.sync(@root)
    expect(result.written).to be(true)
    expect(result.backup).to be_nil
  end

  it "saves a loader without a checksum, as 0.17.0 and earlier copied it, before replacing it" do
    { stimulus => "autoload-0.17.0.js", react => "mount-0.17.0.js" }.each do |file, fixture|
      write(file.path, File.read(File.expand_path("fixtures/managed/#{fixture}", __dir__)))
      expect(file.state(@root)).to eq(:edited)
      expect(file.sync(@root).backup.to_s).to start_with("tmp/rspack_rails/")
    end
  end

  it "saves a hand-edited loader to tmp/rspack_rails before replacing it" do
    write(react.path, "// my own mount.js\n")
    expect(react.state(@root)).to eq(:edited)

    result = react.sync(@root)
    expect(result.backup.to_s).to match(%r{\Atmp/rspack_rails/mount-\d{14}\.js\z})
    expect(read(result.backup)).to eq("// my own mount.js\n")
    expect(react.state(@root)).to eq(:current)
    expect(react.edits_message(result.backup)).to include("import that instead", result.backup.to_s)
  end

  it "tells an edit of a stamped loader from the one rspack_rails wrote" do
    write(stimulus.path, stimulus.content)
    expect(stimulus.edited?(@root)).to be(false)
    write(stimulus.path, stimulus.content.sub('.replace(/_/g, "-")', '.replace(/_/g, "_")'))
    expect(stimulus.edited?(@root)).to be(true)
  end

  it "does not count CRLF line endings, as Git checks files out on Windows, as a change" do
    write(stimulus.path, stimulus.content.gsub("\n", "\r\n"))
    expect(stimulus.state(@root)).to eq(:current)
    expect(stimulus.sync(@root).written).to be(false)

    write(react.path, older_managed(react).gsub("\n", "\r\n"))
    expect(react.state(@root)).to eq(:outdated)
  end
end
